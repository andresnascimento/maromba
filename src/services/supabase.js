import { createClient } from "@supabase/supabase-js";

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseKey = import.meta.env.VITE_SUPABASE_KEY;

// The app has no login yet, so auth session handling is turned off. This avoids
// "Acquiring an exclusive Navigator LockManager lock ... immediately failed"
// errors from the auth token auto-refresh. Remove these options when adding auth.
export const supabase = createClient(supabaseUrl, supabaseKey, {
  auth: {
    persistSession: false,
    autoRefreshToken: false,
    detectSessionInUrl: false,
  },
});
